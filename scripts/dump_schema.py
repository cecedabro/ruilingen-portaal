"""Generate docs/schema.sql and docs/erd.md from the models.

    .venv/bin/python -m scripts.dump_schema

The SQL is what SQLAlchemy would create for `app/models.py` (clean, one column per line); the
production database is built by the migrations and CI's `alembic check` guarantees the two
agree. tests/test_schema_docs.py fails when these files are stale: after changing a model (and
its migration), run this and commit the two files.
"""

import re
from pathlib import Path

from sqlalchemy.dialects import sqlite
from sqlalchemy.schema import CreateIndex, CreateTable, Table

from app import models  # noqa: F401  (registers the tables on Base.metadata)
from app.db import Base

DOCS = Path(__file__).resolve().parent.parent / "docs"

SQL_HEADER = """\
-- The Ruilingen database schema (SQLite), generated from app/models.py.
-- GENERATED by `python -m scripts.dump_schema`; don't edit by hand. Changes go through
-- app/models.py and a migration (docs/architecture.md). Dates are UTC. The live file also has
-- an `alembic_version` table (which migration it is at), left out here. Meaning of each
-- column: docs/database.md.

"""
ERD_HEADER = """\
# Entity relationship diagram

GENERATED by `python -m scripts.dump_schema` from `app/models.py`; don't edit by hand. GitHub
renders the diagram below. Paste the code block into https://mermaid.live to edit it or export
an image. Columns marked "nullable" may be empty; `app_settings` has no relations. What every
column means: [database.md](database.md). The exact SQL: [schema.sql](schema.sql).

```mermaid
"""


def _tables() -> list[Table]:
    return list(Base.metadata.sorted_tables)  # parents before children


def schema_sql() -> str:
    dialect = sqlite.dialect()
    blocks = []
    for table in _tables():
        blocks.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for index in sorted(table.indexes, key=lambda i: i.name):
            blocks.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    return SQL_HEADER + "\n\n".join(blocks) + "\n"


def erd() -> str:
    lines, relations = ["erDiagram"], []
    for table in _tables():
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            base = re.sub(r"\(.*\)", "", str(col.type.compile(dialect=sqlite.dialect())))
            key = "PK" if col.primary_key else ("FK" if col.foreign_keys else "")
            note = ' "nullable"' if col.nullable and not col.primary_key else ""
            lines.append(f"        {base} {col.name}{' ' + key if key else ''}{note}")
            for fk in col.foreign_keys:
                one = "|o" if col.nullable else "||"  # a nullable reference may be absent
                relations.append(
                    f'    {fk.column.table.name} {one}--o{{ {table.name} : "{col.name}"'
                )
        lines.append("    }")
    return ERD_HEADER + "\n".join(lines + relations) + "\n```\n"


def main() -> None:
    (DOCS / "schema.sql").write_text(schema_sql())
    (DOCS / "erd.md").write_text(erd())
    print("written: docs/schema.sql, docs/erd.md")


if __name__ == "__main__":
    main()
